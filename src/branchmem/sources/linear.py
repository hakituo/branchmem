"""Server-side parent attachment for linear sources (chat platforms without a tree).

Such platforms only give arrival order. Without server node IDs every message would
have no parent, the tree would get one root per message, i.e. one world line each.
Inside the same critical section as the write, a new event is attached to the
current tail node of its conversation:

- the node ID is generated by the server (``srv:<event_id>``), auditable and
  recomputable;
- the head is cached in process; on a miss the last line of the conversation file is
  read, so a restart continues the chain;
- an emptied or deleted file yields no head, the event becomes ``partial``; no new root
  is invented and nothing is silently attached to the wrong node.
"""

from __future__ import annotations

import json
import threading
from pathlib import Path
from typing import Dict, Iterable, MutableMapping, Optional

DEFAULT_LINEAR_PLATFORMS = frozenset({"linear"})
SERVER_NODE_PREFIX = "srv:"


def is_linear_source(
    platform: str, client_node_id: str = "", *, platforms: Iterable[str] = DEFAULT_LINEAR_PLATFORMS
) -> bool:
    """Whether the event needs server-side attachment."""
    if str(client_node_id or "").strip():
        return False
    return str(platform or "").strip().lower() in {str(p).lower() for p in platforms}


def server_node_id(event_id: str) -> str:
    return f"{SERVER_NODE_PREFIX}{str(event_id or '').strip()}"


def read_tail_node(file_path: Path) -> str:
    """Node ID of the last event in a JSONL file; empty when unreadable."""
    last = ""
    try:
        with open(file_path, "r", encoding="utf-8") as handle:
            for line in handle:
                if line.strip():
                    last = line
    except OSError:
        return ""
    try:
        payload = json.loads(last) if last else None
    except ValueError:
        return ""
    if not isinstance(payload, dict):
        return ""
    node_id = str(payload.get("client_node_id") or "").strip()
    if node_id:
        return node_id
    event_id = str(payload.get("event_id") or "").strip()
    return server_node_id(event_id) if event_id else ""


class LinearHeadTracker:
    """Current tail node per conversation file; thread-safe, cached in process."""

    def __init__(self) -> None:
        self._heads: Dict[str, str] = {}
        self._lock = threading.RLock()

    @staticmethod
    def _key(file_path: Path) -> str:
        try:
            return str(Path(file_path).resolve())
        except OSError:
            return str(file_path)

    def head(self, file_path: Path) -> str:
        key = self._key(file_path)
        with self._lock:
            if key not in self._heads:
                self._heads[key] = read_tail_node(file_path)
            return self._heads[key]

    def advance(self, file_path: Path, node_id: str) -> None:
        value = str(node_id or "").strip()
        if value:
            with self._lock:
                self._heads[self._key(file_path)] = value

    def forget(self, file_path: Path) -> None:
        with self._lock:
            self._heads.pop(self._key(file_path), None)

    def clear(self) -> None:
        with self._lock:
            self._heads.clear()


def attach_linear_parent(
    payload: MutableMapping[str, object],
    *,
    file_path: Path,
    platform: str,
    tracker: LinearHeadTracker,
    platforms: Iterable[str] = DEFAULT_LINEAR_PLATFORMS,
) -> Optional[str]:
    """Fill ``client_node_id`` / ``parent_node_id`` of a linear-source event.

    Returns the parent attached to (empty for the first node of the file).
    """
    node_id = str(payload.get("client_node_id") or "").strip()
    if node_id:
        return str(payload.get("parent_node_id") or "")
    if not is_linear_source(platform, node_id, platforms=platforms):
        return ""
    event_id = str(payload.get("event_id") or "").strip()
    if not event_id:
        return ""
    parent = tracker.head(file_path)
    payload["client_node_id"] = server_node_id(event_id)
    payload["parent_node_id"] = parent
    payload["topology_status"] = "complete" if parent else "partial"
    return parent
